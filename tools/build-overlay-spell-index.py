"""Extract an offline Retail spell index from the pinned, locally built SimC data.

No network requests. Re-run after deliberately updating the simulator data pin.
The source is the same verified archive used by build-sim-provider.py.
"""
from pathlib import Path
import ast
import gzip
import hashlib
import json
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
COMMIT = 'fa22f84d2a13255d7325826f89a46bbb9181233d'
SOURCE = ROOT / '.build/sim-providers/source' / ('simc-' + COMMIT)
TARGET = ROOT / 'internal/spellbook'


def fields(line):
    """Split a generated C initializer without splitting strings or subarrays."""
    line = line.strip()
    if not line.startswith('{ '):
        return []
    out, start, depth, quoted, escaped = [], 1, 0, False, False
    for i, char in enumerate(line[1:], 1):
        if quoted:
            if escaped:
                escaped = False
            elif char == '\\':
                escaped = True
            elif char == '"':
                quoted = False
        elif char == '"':
            quoted = True
        elif char == '{':
            depth += 1
        elif char == '}':
            if depth == 0:
                out.append(line[start:i].strip())
                return out
            depth -= 1
        elif char == ',' and depth == 0:
            out.append(line[start:i].strip())
            start = i + 1
    return []


def text(value):
    return ast.literal_eval(value) if value.startswith('"') else ''


def readable(value, buff=False):
    # Use the base branch of talent conditionals. Leave numerical substitutions
    # visibly unspecified; never present raw tooltip code as resolved live values.
    if '$?' in value and not buff:
        return ''
    value = re.sub(r'\|c[0-9a-f]{8}|\|r', '', value, flags=re.I)
    value = re.sub(r'\|n', ' ', value, flags=re.I)
    for _ in range(8):
        newer = re.sub(r'\$\?[^\[\s]+\[([^\[\]]*)\]\[([^\[\]]*)\]', r'\2', value)
        if newer == value:
            break
        value = newer
    if any(token in value for token in ('$?', '$@', '${', '|T', '|A')):
        return ''
    value = re.sub(r'\$l([^:;]*):([^;]*);', r'\2', value)
    value = re.sub(r'\$[*/][^;\s]+;[a-z]\d+|\$<[^>]+>|\$\w+', '…', value)
    if '$' in value or '|' in value:
        return ''
    value = re.sub(r'\s+', ' ', value).strip()
    return value[:240]


def build():
    generated = SOURCE / 'engine/dbc/generated'
    spellfile = generated / 'sc_spell_data.inc'
    textfile = generated / 'spelltext_data.inc'
    source = spellfile.read_text()
    header = re.search(r'// (\d+) spells, wow build level ([\d.]+)', source)
    if not header:
        raise ValueError('Unrecognized spell data header')
    build = header[2]
    spells, aura_ids = {}, set()
    section = ''
    for line in source.splitlines():
        if line.startswith('static '):
            section = 'spells' if '__spell_data[' in line else 'effects' if '__spelleffect_data[' in line else ''
        if not section:
            continue
        row = fields(line)
        if not row:
            continue
        if section == 'spells':
            spell_id = int(row[1])
            spells[spell_id] = {'id': spell_id, 'name': text(row[0]), 'mask': int(row[7], 0),
                                'duration': float(row[28]) / 1000, 'stacks': int(row[29])}
        elif int(row[3]) in (6, 27, 35, 65, 119, 128, 129, 143, 174, 202, 271):
            aura_ids.add(int(row[1]))
    if len(spells) != int(header[1]):
        raise ValueError('Spell count changed during extraction')
    section = False
    for line in textfile.read_text().splitlines():
        if line.startswith('static '):
            section = '__spelltext_data ' in line
        if not section:
            continue
        row = fields(line)
        if not row or not row[0].isdigit():
            continue
        spell = spells.get(int(row[0]))
        if not spell:
            continue
        buff = text(row[2])
        if buff:
            aura_ids.add(spell['id'])
            spell['tooltip'] = True
        description = readable(buff or text(row[1]), bool(buff))
        if description:
            spell['description'] = description
    for spell_id, spell in spells.items():
        spell['aura'] = spell_id in aura_ids
    payload = {'build': build, 'commit': COMMIT, 'spells': sorted(spells.values(), key=lambda s: s['id'])}
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / 'retail.json.gz').write_bytes(gzip.compress(json.dumps(payload, ensure_ascii=False, separators=(',', ':')).encode(), mtime=0))
    shutil.copyfile(SOURCE / 'COPYING', TARGET / 'LICENSE.txt')
    (TARGET / 'NOTICE.md').write_text(
        '# Retail spell index\n\nGenerated by `Tools/build-overlay-spell-index.py` from SimulationCraft\n'
        f'commit [{COMMIT}](https://github.com/simulationcraft/simc/commit/{COMMIT}).\n'
        f'Game data build: **{build}**; locale: English. {len(spells):,} spells.\n\n'
        'Source files: `engine/dbc/generated/sc_spell_data.inc` and `spelltext_data.inc`.\n'
        'Names, IDs, class masks, aura effects and base tooltip text are indexed.\n'
        'Talent conditionals use the base branch; unresolved values show an ellipsis.\n'
        'The index is a lookup aid, not a list of currently learned/active spells.\n'
        'It is not a complete database of every encounter spell or newer hotfix.\n\n'
        'SimulationCraft contributors retain their copyrights and attribution.\n'
        'The source dataset is distributed under GPL v3; see LICENSE.txt.\n'
        'WoW spell names and game data originate with Blizzard Entertainment.\n'
        'The engine embeds the index, this notice and the license; the manager exposes\n'
        'the notice and license through its Help menu.\n\n'
        + '\n'.join(f'- `{p.name}` SHA256 `{hashlib.sha256(p.read_bytes()).hexdigest()}`' for p in (spellfile, textfile)) + '\n')
    print(f'Indexed {len(spells)} Retail spells ({build}); {sum(s["aura"] for s in spells.values())} aura entries')


if __name__ == '__main__':
    build()
